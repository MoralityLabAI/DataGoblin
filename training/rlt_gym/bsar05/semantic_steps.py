"""BSAR-05: exact arithmetic gym for recurrent proof-scope repair.

Every matched pair differs by one of the genuine premises of
SweetbrierBSARStep7.LerayDoublingChain.step. Labels are generated by
exact integer checks, not by language templates or purported Lean proofs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

SOURCE_COMMIT = "80c62433b0eb671175bd8d6169822d3ebd922b60"
SOURCE_THEOREM = "SweetbrierBSARStep7.LerayDoublingChain.step"
SEED = 2026112205
LABELS = ("ADMISSIBLE", "REJECTED")
SPLITS = {
    "train": (range(1, 5), range(1, 26)),
    "dev": (range(5, 7), range(26, 41)),
    "test": (range(7, 10), range(41, 56)),
}
MODES = ("next_nonnegative", "half_budget", "window_ode")


@dataclass(frozen=True)
class Step:
    m: int
    im: int
    previous: int
    next_state: int


def premises(step: Step) -> dict[str, bool]:
    return {
        "m_positive": step.m > 0,
        "next_nonnegative": step.next_state >= 0,
        "half_budget": 2 * step.im <= step.m,
        "window_ode": step.m * (step.next_state - step.previous) <= step.im * step.next_state,
    }


def allowed(step: Step) -> bool:
    return all(premises(step).values())


def samples(split: str) -> list[dict[str, Any]]:
    if split not in SPLITS:
        raise ValueError("Unknown source split")
    q_values, p_values = SPLITS[split]
    result = []
    for q in q_values:
        for p in p_values:
            for mode_id, mode in enumerate(MODES):
                prev = 3 * p + mode_id
                positive = Step(m=2 * q, im=q, previous=prev, next_state=2 * prev)
                if mode == "next_nonnegative":
                    negative = Step(m=2 * q, im=q, previous=prev, next_state=-1)
                elif mode == "half_budget":
                    negative = Step(m=2 * q, im=q + 1, previous=prev, next_state=2 * prev)
                else:
                    negative = Step(m=2 * q, im=q, previous=prev, next_state=2 * prev + 1)
                if not allowed(positive):
                    raise AssertionError("Invalid positive source witness")
                failed = [name for name, passed in premises(negative).items() if not passed]
                if failed != [mode]:
                    raise AssertionError(f"Unmatched violated premise: {failed} != {mode}")
                identity = f"{SOURCE_COMMIT}:{split}:{q}:{p}:{mode}"
                pair_id = hashlib.sha256(identity.encode()).hexdigest()[:20]
                for label, step in (("ADMISSIBLE", positive), ("REJECTED", negative)):
                    task_id = hashlib.sha256(f"{identity}:{label}".encode()).hexdigest()[:20]
                    prompt = (
                        "Evaluate the exact premises of the pinned Lean arithmetic rule "
                        "LerayDoublingChain.step. The outer closure requires M > 0. "
                        "The local hypotheses require d_next >= 0, "
                        "M*(d_next-d_prev) <= I_m*d_next, and 2*I_m <= M. "
                        f"Given M={step.m}, I_m={step.im}, d_prev={step.previous}, "
                        f"d_next={step.next_state}, may this step be applied? "
                        "Reply ADMISSIBLE or REJECTED."
                    )
                    result.append({
                        "id": task_id,
                        "pair_id": pair_id,
                        "split": split,
                        "source_commit": SOURCE_COMMIT,
                        "source_theorem": SOURCE_THEOREM,
                        "root": identity,
                        "prompt": prompt,
                        "parameters": asdict(step),
                        "gold_label": label,
                        "oracle_gates": premises(step),
                        "mutation_gate": mode if label == "REJECTED" else None,
                        "oracle_kind": "exact_python_integer_arithmetic",
                    })
    return result


def generate(seed: int = SEED) -> list[dict[str, Any]]:
    data = [row for split in SPLITS for row in samples(split)]
    random.Random(seed).shuffle(data)
    return data


def validate(data: list[dict[str, Any]]) -> dict[str, Any]:
    pair_to_rows: dict[str, list[dict[str, Any]]] = defaultdict(list)
    ids = set()
    for row in data:
        if row["id"] in ids:
            raise ValueError("Duplicate example ID")
        ids.add(row["id"])
        pair_to_rows[row["pair_id"]].append(row)
        step = Step(**row["parameters"])
        actual = "ADMISSIBLE" if allowed(step) else "REJECTED"
        if actual != row["gold_label"]:
            raise ValueError("Oracle label mismatch")
        if row["oracle_gates"] != premises(step):
            raise ValueError("Oracle gate trace mismatch")
    if any(len(pair) != 2 or {r["gold_label"] for r in pair} != set(LABELS)
           or len({r["split"] for r in pair}) != 1 for pair in pair_to_rows.values()):
        raise ValueError("Broken paired-label custody")
    result = {
        "source_commit": SOURCE_COMMIT,
        "examples": len(data),
        "pairs": len(pair_to_rows),
        "by_split": dict(Counter(row["split"] for row in data)),
        "by_mutation": dict(Counter(row["mutation_gate"] for row in data if row["mutation_gate"])),
        "source_semantics": "exact synthetic integer rule, not native Lean or PDE evidence",
    }
    if set(result["by_split"]) != set(SPLITS):
        raise ValueError("Missing holdout split")
    return result


def public_test(data: list[dict[str, Any]]) -> list[dict[str, str]]:
    return [{"id": row["id"], "pair_id": row["pair_id"], "prompt": row["prompt"]}
            for row in sorted(data, key=lambda x: x["id"]) if row["split"] == "test"]


def score(data: list[dict[str, Any]], responses: dict[str, str]) -> dict[str, Any]:
    test = {r["id"]: r for r in data if r["split"] == "test"}
    if not set(responses) <= set(test):
        raise ValueError("Predictions include IDs outside test")
    if any(label not in (*LABELS, "ABSTAIN") for label in responses.values()):
        raise ValueError("Unknown predicted label")
    answered = sum(responses.get(key, "ABSTAIN") != "ABSTAIN" for key in test)
    correct = sum(responses.get(key, "ABSTAIN") == row["gold_label"]
                  for key, row in test.items())
    groups: dict[str, list[str]] = defaultdict(list)
    for key, row in test.items():
        groups[row["pair_id"]].append(key)
    complete = sum(all(responses.get(k) == test[k]["gold_label"] for k in keys)
                   for keys in groups.values())
    return {
        "total": len(test),
        "coverage": answered / len(test),
        "strict_accuracy": correct / len(test),
        "selective_accuracy": correct / answered if answered else 0.0,
        "complete_pairs": complete,
        "pairs": len(groups),
        "scope": "exact integer premise matching",
    }


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> str:
    content = "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows).encode()
    path.write_bytes(content)
    return hashlib.sha256(content).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()
    rows = generate(args.seed)
    summary = validate(rows)
    args.out.mkdir(parents=True, exist_ok=True)
    hashes = {}
    for split in SPLITS:
        subset = [r for r in rows if r["split"] == split]
        hashes[split] = write_jsonl(args.out / f"{split}.jsonl", subset)
    hashes["public_test"] = write_jsonl(args.out / "public_test.jsonl", public_test(rows))
    majority = {r["id"]: "ADMISSIBLE" for r in rows if r["split"] == "test"}
    summary["constant_baseline"] = score(rows, majority)
    summary["sha256"] = hashes
    summary["seed"] = args.seed
    (args.out / "manifest.json").write_text(json.dumps(summary, sort_keys=True, indent=2) + "\n")
    print(json.dumps(summary, sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
