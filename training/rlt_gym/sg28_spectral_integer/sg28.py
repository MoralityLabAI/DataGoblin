def solve(task, initial, *, cap=63, use_milp=True, root=None):
    if type(cap) is not int or not 1<=cap<=127:raise TaskError('invalid proof cap')
    q=validate(task);tick=time.process_time_ns();box=domains(q);model=Model(q)
    schedule=list(initial);L=score(q,schedule)['objective'];initial_value=L;calls=0;milp_status=None
    if root is None:root=(root_vector(q),1)
    root_eta,root_den=root
    root_upper=conditioned(q,box,list(root_eta),root_den)
    if use_milp and root_upper>L:
        candidate,milp_status=model.primal(box)
        if candidate is not None and score(q,candidate)['objective']>L:schedule=candidate;L=score(q,schedule)['objective']
    milp_value=L
    tree={};heap=[];nodes=1;seq=0
    def prepare(node,box,proposal):
        nonlocal L,schedule,calls,seq
        w=infeasible(q,box)
        if w is not None:node.update(kind='infeasible',witness=w);return
        e,d=proposal;u=conditioned(q,box,list(e),d);h=None
        if u>L:
            p,h=model.solve(box);calls+=1
            if p is not None:
                v,c=p;v=list(v);b=conditioned(q,box,v,c)
                if b<=u:e,d,u=v,c,b
        node.update(kind='bound',eta=list(e),den=d,upper=u)
        # Integral retention histories imply an exact conditional row optimum.
        # Recover a legal candidate independently of numerical y or LP status.
        if h is not None and all(abs(float(v)-round(float(v)))<=1e-6 for v in h.flat):
            last=[int(round(sum(h[:,j]))) for j in range(q['d'])]
            if all(lo<=v<=hi for v,(lo,hi) in zip(last,box,strict=True)):
                a=fixed_schedule(q,tuple((v,v) for v in last))
                if a is not None and score(q,a)['objective']>L:
                    schedule=a;L=score(q,a)['objective']
        if u<=L:return
        a=fixed_schedule(q,box)
        if a is not None:
            v=score(q,a)['objective']
            if v>L:schedule=a;L=v
            # Exact row cutoffs for all fixed-last domains.
            e=[]
            for i,k in enumerate(q['k'],1):
                vals=sorted((q['u'][i-1][j] for j,(lo,_) in enumerate(box) if lo>i),reverse=True)
                n=k-sum(lo==i for lo,_ in box)
                e.append(vals[0] if n==0 and vals else vals[n-1] if n else 0)
            u=conditioned(q,box,e,1);assert u==v
            node.update(eta=e,den=1,upper=u);return
        # Fractional retention variable nearest 1/2, deterministic ties.
        options=[(abs(float(h[i-1,j])-.5),j,i-1) for j,(lo,hi) in enumerate(box) for i in range(lo+1,hi+1) if h is not None and 1e-6<h[i-1,j]<1-1e-6]
        if options:_,j,cut=min(options)
        else:
            j=max(range(q['d']),key=lambda j:box[j][1]-box[j][0]);lo,hi=box[j];cut=(lo+hi)//2
        seq+=1;heappush(heap,(-u,seq,node,box,j,cut))
    prepare(tree,box,root)
    root_floor=tree['upper']
    while heap and nodes+2<=cap:
        neg,_,node,box,j,cut=heappop(heap)
        if -neg<=L:break
        p=(node['eta'],node['den']);children=[{},{}];node.clear();node.update(kind='split',j=j,cut=cut,children=children);nodes+=2
        for child,b in zip(children,split(q,box,j,cut),strict=True):prepare(child,b,p)
    def aggregate(n):
        if n['kind']=='bound':return n['upper'],1,0
        if n['kind']=='infeasible':return None,1,0
        a,b=[aggregate(v) for v in n['children']];vals=[v[0] for v in (a,b) if v[0] is not None]
        return max(vals) if vals else None,1+a[1]+b[1],1+max(a[2],b[2])
    upper,n,depth=aggregate(tree);assert n==nodes and upper is not None and upper>=L
    r=dict(schedule=schedule,objective=L,upper=upper,gap=upper-L,nodes=n,depth=depth,tree=tree,initial=initial_value,initial_upper=root_upper,root_floor=root_floor,milp_value=milp_value,milp_status=milp_status,lp_calls=calls,cpu_ns=time.process_time_ns()-tick)
    replay(q,r,cap);return r


def exposed():
    """Frozen archived SG-27 inputs; SG-26 regenerated by its pinned generator."""
    for row in json.loads(Path('sg28_exposed_inputs.json').read_text()):
        q=row['task']; a=row['initial']; p=row['root']; prior=row['prior_upper']
        if p is not None:
            c=verify_certificate(q,a,*p)
            assert c['integer_upper']>=prior
        yield row['label'],q,a,p,prior


def campaign():
    rows=[]
    for label,q,a,root,prior_upper in exposed():
        r=solve(q,a,cap=63,root=root)
        if prior_upper is not None:assert r['objective']<=prior_upper and r['upper']>=score(q,a)['objective']
        rows.append(dict(label=label,task=q,initial=a,prior_upper=prior_upper,receipt=r))
        print(label,r['objective'],r['upper'],r['nodes'],r['lp_calls'],round(r['cpu_ns']/1e6,2),flush=True)
        Path('sg28_exposed.json').write_text(json.dumps(rows))
    fresh=[]
    for j,reg in enumerate(('persistent','rotating','mixed')):
        for i in range(6):
            seed=2810000+j*1000+i;q=sg07.task(seed,reg,32,12);q['k']=[7+(seed+v)%2 for v in range(q['T'])]
            a=sg11.initial(q);r=solve(q,a,cap=63);fresh.append(dict(seed=seed,regime=reg,task=q,initial=a,receipt=r))
            print('fresh',seed,r['objective'],r['upper'],r['nodes'],r['lp_calls'],round(r['cpu_ns']/1e6,2),flush=True)
            Path('sg28_fresh.json').write_text(json.dumps(fresh))

if __name__=='__main__':campaign()
